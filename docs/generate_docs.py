NAVY   = RGBColor(0x1e, 0x40, 0xaf)
GREEN  = RGBColor(0x15, 0x80, 0x3d)
AMBER  = RGBColor(0xb4, 0x5a, 0x00)
MUTED  = RGBColor(0x64, 0x74, 0x8b)
DARK   = RGBColor(0x1e, 0x3a, 0x5f)

def h1(text):
    p = doc.add_heading(text, level=1)
    p.runs[0].font.color.rgb = NAVY
    p.runs[0].font.size = Pt(22)
    p.paragraph_format.space_before = Pt(18)
    return p

def h2(text):
    p = doc.add_heading(text, level=2)
    p.runs[0].font.color.rgb = NAVY
    p.runs[0].font.size = Pt(15)
    p.paragraph_format.space_before = Pt(10)
    return p

def h3(text):
    p = doc.add_heading(text, level=3)
    p.runs[0].font.color.rgb = GREEN
    p.runs[0].font.size = Pt(12)
    return p

def status_badge(text, color=None):
    p = doc.add_paragraph()
    run = p.add_run(f'  {text}  ')
    run.bold = True
    run.font.size = Pt(9)
    run.font.color.rgb = color or GREEN
    p.paragraph_format.space_after = Pt(2)
    return p

def para(text, space_after=6):
    p = doc.add_paragraph()
    p.add_run(text)
    p.paragraph_format.space_after = Pt(space_after)
    return p

def bullet(text, bold_part=None, level=0):
    p = doc.add_paragraph(style='List Bullet')
    if bold_part:
        r = p.add_run(bold_part)
        r.bold = True
        r.font.color.rgb = DARK
        p.add_run(' — ' + text)
    else:
        p.add_run(text)
    p.paragraph_format.space_after = Pt(2)
    p.paragraph_format.left_indent = Cm(level * 0.5)
    return p

def divider():
    p = doc.add_paragraph()
    run = p.add_run('─' * 70)
    run.font.color.rgb = RGBColor(0xcc, 0xd5, 0xe0)
    run.font.size = Pt(9)
    p.paragraph_format.space_after = Pt(2)

